HOUR_BAG = [h for h, w in enumerate(HOUR_WEIGHTS) for _ in range(w)]


def wpick(rng, pairs):
    names, weights = zip(*pairs)
    return rng.choices(names, weights=weights, k=1)[0]


def make_viewers(rng, n):
    rows, start, end = [], date(2022, 1, 1), date(2026, 5, 31)
    span = (end - start).days
    for i in range(1, n + 1):
        f, l = rng.choice(FIRST), rng.choice(LAST)
        signup = start + timedelta(days=int(span * (rng.random() ** 0.6)))
        rows.append({"viewer_id": f"V{i:05d}", "full_name": f"{f} {l}",
                     "email": f"{f.lower()}.{l.lower().replace(chr(39), '')}{i}@example.com",
                     "city": wpick(rng, CITIES), "country": "IN", "signup_date": signup.isoformat(),
                     "birth_year": rng.randint(1960, 2007),
                     "plan_id": rng.choices([p[0] for p in PLANS], weights=[p[5] for p in PLANS])[0],
                     "referral_code": f"REF{rng.randint(1000, 9999)}" if rng.random() < 0.25 else ""})
    return rows


def make_titles(rng, n):
    titles, seen = [], set()
    for i in range(1, n + 1):
        name = None
        while name is None or name in seen:
            base = f"The {rng.choice(ADJ)} {rng.choice(NOUN)}" if rng.random() < 0.5 else f"{rng.choice(ADJ)} {rng.choice(NOUN)}"
            name = base if base not in seen else f"{base} {rng.randint(2, 4)}"
        seen.add(name)
        is_series = rng.random() < 0.4
        titles.append({
            "title_id": f"T{i:04d}", "title": name, "type": "series" if is_series else "movie",
            "release_year": rng.randint(2005, 2026),
            "runtime_min": rng.randint(22, 60) if is_series else rng.randint(85, 175),
            "language": wpick(rng, LANGS),
            "maturity_rating": rng.choice(["U", "U/A 7+", "U/A 13+", "U/A 16+", "A"]),
            "genres": rng.sample(GENRES, k=rng.choice([1, 2, 2, 3])),
            "seasons": rng.randint(1, 6) if is_series else None,
            "cast_members": [{"name": a, "role": "lead" if k == 0 else "supporting"}
                             for k, a in enumerate(rng.sample(ACTORS, k=rng.randint(2, 4)))],
            "metadata": {"studio": rng.choice(STUDIOS), "critic_score": round(rng.uniform(4.5, 9.6), 1),
                         "is_original": rng.random() < 0.3}})
    return titles


def write_text(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="") as f:
        f.write(text)


def write_csv(path, rows):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        w.writeheader()
        w.writerows(rows)


def write_messy(path, viewers):
    """Legacy export with the usual problems: ';' delimiter, a preamble line, dd/mm/yyyy dates, 'N/A' nulls,
    'Last; First' names, duplicate rows and one broken row with an extra column."""
    lines = ["# exported from LegacyCRM v2 on 03/01/2026",
             "ViewerID;Full Name;E-mail;City;Signup Date;Monthly Spend (INR);Active"]
    price = {p[0]: p[2] for p in PLANS}
    for k, v in enumerate(viewers[:300]):
        d = date.fromisoformat(v["signup_date"]).strftime("%d/%m/%Y")
        first, last = v["full_name"].split(" ", 1)
        name = v["full_name"] if k % 37 else f'"{last}; {first}"'
        lines.append(";".join([v["viewer_id"], name, v["email"] if k % 23 else "N/A", v["city"] if k % 29 else "", d,
                               f"{price[v['plan_id']]:.2f}" if k % 31 else "N/A", "Y" if k % 9 else "N"]))
        if k % 50 == 0:
            lines.append(";".join([v["viewer_id"], name, v["email"], v["city"], d, f"{price[v['plan_id']]:.2f}", "Y"]))
    lines.append("V99999;Broken Row;broken@example.com;Pune;31/02/2026;199.00;Y;EXTRA_COLUMN")
    write_text(path, "\r\n".join(lines) + "\r\n")


t0 = time.time()
rng = random.Random(42)
viewers = make_viewers(rng, N_VIEWERS)
titles = make_titles(rng, N_TITLES)
write_csv(f"{RAW}/plans.csv", [dict(plan_id=p[0], plan_name=p[1], monthly_price_inr=p[2], max_screens=p[3],
                                    video_quality=p[4]) for p in PLANS])
write_csv(f"{RAW}/viewers.csv", viewers)
