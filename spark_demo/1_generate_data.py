"""
1_generate_data.py - builds the StreamVerse dataset for the PySpark course.

StreamVerse is an imaginary Netflix-style streaming service in India. Output (under DATA/raw):

  plans.csv                               4 subscription plans
  viewers.csv                             viewers (customers)
  titles.jsonl                            movies and series, one JSON object per line, with nested fields
  playback/month=YYYY-MM/part-*.parquet   viewing sessions (the big table), partitioned by month
  payments/month=YYYY-MM/part-*.csv       subscription payments, one CSV folder per month
  events/month=YYYY-MM/part-*.json        app events as JSON lines, with nested objects
  messy/viewers_legacy_export.csv         a deliberately messy CSV for the data-cleaning lessons

Small tables are made with plain Python and a fixed random seed; the big ones are generated by Spark
itself from hash functions, so the same settings always give the same rows on any machine.
"""
