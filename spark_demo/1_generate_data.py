print(f"small tables: {len(viewers):,} viewers, {len(titles):,} titles, {len(PLANS)} plans")

# --- the big tables, generated by Spark ---------------------------------------------------------
def u(col, salt):
    """A repeatable random number in [0, 1) from a column and a salt."""
    return F.pmod(F.xxhash64(col, F.lit(salt)), F.lit(1_000_003)) / F.lit(1_000_003.0)


# viewers and titles get a shuffled index so popularity does not follow ID order
vi = (spark.createDataFrame([(v["viewer_id"], v["signup_date"], v["plan_id"]) for v in viewers],
                            "viewer_id string, signup_date string, plan_id int")
      .withColumn("signup_date", F.to_date("signup_date"))
      .withColumn("vidx", F.row_number().over(Window.orderBy(F.xxhash64("viewer_id", F.lit("#")))) - 1))
ti = (spark.createDataFrame([(t["title_id"], t["runtime_min"]) for t in titles], "title_id string, runtime_min int")
      .withColumn("tidx", F.row_number().over(Window.orderBy(F.xxhash64("title_id", F.lit("#")))) - 1))
hour_bag = F.array(*[F.lit(h) for h in HOUR_BAG])

s = (spark.range(N_SESSIONS)
     .withColumn("vidx", F.floor(F.lit(N_VIEWERS) * F.pow(u("id", "v"), 1.6)).cast("int"))
     # one viral hit takes ~12% of all sessions (very uneven data, useful later for performance tuning)
     .withColumn("tidx", F.when(u("id", "hit") < 0.12, F.lit(0))
                 .otherwise(F.floor(F.lit(N_TITLES) * F.pow(u("id", "t"), 2.2))).cast("int"))
     .withColumn("started_at",
                 F.lit("2026-01-01 00:00:00").cast("timestamp")
                 + F.make_dt_interval(F.floor(u("id", "d") * 181).cast("int"),
                                      F.element_at(hour_bag, (F.floor(u("id", "h") * len(HOUR_BAG)) + 1).cast("int")),
                                      F.floor(u("id", "m") * 60).cast("int"),
                                      F.floor(u("id", "s") * 60).cast("int")))
     .withColumn("device", F.when(u("id", "dev") < 0.46, "Smart TV").when(u("id", "dev") < 0.80, "Mobile")
                 .when(u("id", "dev") < 0.93, "Web").otherwise("Tablet"))
     .withColumn("uw", u("id", "w")).withColumn("ub", u("id", "b")))

playback = (s.join(F.broadcast(vi), "vidx").join(F.broadcast(ti), "tidx")
            .where(F.col("started_at") >= F.col("signup_date"))
            .select((F.col("id") + 1).alias("session_id"), "viewer_id", "title_id", "device", "started_at",
                    F.when(F.col("uw") < 0.35, F.col("runtime_min") * 60 * (0.9 + 0.1 * F.col("ub")))
                     .otherwise(F.col("runtime_min") * 60 * F.col("uw") * 0.9).cast("int").alias("watch_seconds"),
                    F.when(F.col("device") == "Mobile", 1500 + (F.col("ub") * 1500).cast("int"))
                     .otherwise(3000 + (F.col("ub") * 13000).cast("int")).alias("bitrate_kbps"),
                    "runtime_min"))
playback = playback.withColumn("completed", F.col("watch_seconds") >= F.col("runtime_min") * 60 * 0.9).drop("runtime_min")
# ~0.1% of sessions are delivered twice by the (imaginary) mobile SDK - a real duplicate problem to fix later
playback = playback.unionByName(playback.where(F.col("session_id") % 997 == 0))
(playback.withColumn("month", F.date_format("started_at", "yyyy-MM"))
 .repartition("month").sortWithinPartitions("month", "started_at")
 .write.mode("overwrite").partitionBy("month").parquet(f"{RAW}/playback"))
n_play = spark.read.parquet(f"{RAW}/playback").count()
print(f"playback: {n_play:,} rows -> Parquet, partitioned by month")

# --- payments: one charge per viewer per month after signup; ~3% fail and are retried ----------
price = spark.createDataFrame([(p[0], p[2]) for p in PLANS], "plan_id int, price int")
months = spark.range(1, 7).withColumnRenamed("id", "mon")
base = (vi.crossJoin(months).join(F.broadcast(price), "plan_id")
        .where(F.make_date(F.lit(2026), F.col("mon").cast("int"), F.lit(28)) >= F.col("signup_date"))
        .withColumn("k", F.concat_ws("-", "viewer_id", "mon"))
        .withColumn("paid_at", F.make_timestamp(F.lit(2026), F.col("mon").cast("int"),
                                                (1 + u("k", "day") * 27).cast("int"), (u("k", "hr") * 23).cast("int"),
                                                F.lit(15), F.lit(0)))
        .withColumn("r1", u("k", "status")).withColumn("r2", u("k", "method")))
first_try = base.select("viewer_id", "mon", "paid_at", F.col("price").alias("amount_inr"), F.lit(1).alias("attempt"),
                        F.when(F.col("r2") < 0.55, "UPI").when(F.col("r2") < 0.82, "Card")
                         .when(F.col("r2") < 0.93, "NetBanking").otherwise("Wallet").alias("method"),
                        F.when(F.col("r1") < 0.03, "failed").when(F.col("r1") > 0.995, "refunded")
                         .otherwise("success").alias("status"))
retry = base.where(F.col("r1") < 0.03).select("viewer_id", "mon", (F.col("paid_at") + F.expr("INTERVAL 2 HOURS")).alias("paid_at"),
                                              F.col("price").alias("amount_inr"), F.lit(2).alias("attempt"), F.lit("UPI").alias("method"),
                                              F.lit("success").alias("status"))
payments = (first_try.unionByName(retry)
            .withColumn("payment_id", F.concat(F.lit("P"), F.date_format("paid_at", "yyyyMM"),
                                               F.substring("viewer_id", 2, 5), F.col("attempt").cast("string")))
            .withColumn("month", F.date_format("paid_at", "yyyy-MM"))
            .select("payment_id", "viewer_id", F.date_format("paid_at", "yyyy-MM-dd HH:mm:ss").alias("paid_at"),
                    "amount_inr", "method", "status", "month"))
(payments.repartition("month").sortWithinPartitions("month", "paid_at", "viewer_id")
 .write.mode("overwrite").partitionBy("month").option("header", True).csv(f"{RAW}/payments"))
print(f"payments: {spark.read.option('header', True).csv(f'{RAW}/payments').count():,} rows -> CSV, partitioned by month")

# --- app events: JSON lines with nested objects; the keys inside `properties` depend on the event type
ev = (spark.range(EVENTS_PER_MONTH * 6)
      .withColumn("mon", (F.col("id") % 6 + 1).cast("int"))
      .withColumn("ue", u("id", "e")).withColumn("uo", u("id", "o"))
      .withColumn("vidx", F.floor(F.lit(N_VIEWERS) * F.pow(u("id", "ev"), 1.6)).cast("int"))
      .withColumn("tidx", F.floor(F.lit(N_TITLES) * F.pow(u("id", "et"), 2.2)).cast("int"))
      .withColumn("ts", F.make_timestamp(F.lit(2026), "mon", F.lit(1), F.lit(0), F.lit(0), F.lit(0))
                  + F.make_dt_interval(F.lit(0), F.lit(0), F.lit(0), (u("id", "ts") * 86400 * 28).cast("int")))
      .join(F.broadcast(vi.select("vidx", "viewer_id")), "vidx").join(F.broadcast(ti), "tidx"))
etype = (F.when(F.col("ue") < 0.30, "search").when(F.col("ue") < 0.62, "play").when(F.col("ue") < 0.80, "pause")
         .when(F.col("ue") < 0.92, "add_to_list").otherwise("rating"))
events = (ev.withColumn("event_type", etype)
          .select(F.concat(F.lit("E"), F.lpad(F.col("id").cast("string"), 8, "0")).alias("event_id"),
                  F.date_format("ts", "yyyy-MM-dd'T'HH:mm:ss'Z'").alias("ts"), "viewer_id", "event_type",
                  F.struct(F.when(F.col("event_type") != "search", F.col("title_id")).alias("title_id"),
                           F.when(F.col("event_type") == "search", F.element_at(F.array(*[F.lit(w.lower()) for w in NOUN]),
                                                                         (F.floor(F.col("uo") * len(NOUN)) + 1).cast("int"))).alias("query"),
                           F.when(F.col("event_type") == "search", (F.col("uo") * 40).cast("int")).alias("results"),
                           F.when(F.col("event_type") == "pause", (F.col("uo") * F.col("runtime_min") * 60).cast("int"))
                            .when(F.col("event_type") == "play", F.lit(0)).alias("position_sec"),
                           F.when(F.col("event_type") == "rating", (1 + (F.col("uo") * 5).cast("int") % 5)).alias("stars")
                           ).alias("properties"),
                  F.struct(F.when(F.col("uo") < 0.55, "android").when(F.col("uo") < 0.75, "ios")
                            .when(F.col("uo") < 0.92, "tizen").otherwise("web").alias("os"),
                           F.concat(F.lit("5."), ((F.col("uo") * 7).cast("int") + F.col("mon")).cast("string")).alias("app_version")
                           ).alias("device"),
                  F.date_format("ts", "yyyy-MM").alias("month")))
(events.repartition("month").sortWithinPartitions("month", "ts")
 .write.mode("overwrite").partitionBy("month").json(f"{RAW}/events"))       # NULL fields are left out of the JSON
print(f"events: {spark.read.json(f'{RAW}/events').count():,} rows -> JSON lines, partitioned by month")
print(f"done in {time.time() - t0:.0f} s -> {os.path.abspath(RAW)}")