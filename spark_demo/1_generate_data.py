N_TITLES = 500
N_SESSIONS = 2_000_000          # before the "signed up yet?" filter and the duplicate rows
EVENTS_PER_MONTH = 50_000
if "--small" in sys.argv:              # python 1_generate_data.py --small
    N_VIEWERS, N_SESSIONS, EVENTS_PER_MONTH = 5_000, 300_000, 10_000

